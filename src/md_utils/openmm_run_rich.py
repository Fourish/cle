class DetailProgress(Progress):
    """Keep live measurements below the bar, also on narrow terminals."""

    def get_renderables(self) -> Iterator[ConsoleRenderable]:
        yield self.make_tasks_table(self.tasks)
        for task in self.tasks:
            detail: str = str(task.fields.get("detail", ""))
            if detail:
                yield Text(detail)


class TerminalProgress:
    """Rich display only; completed counts never control the simulation."""

    def __init__(self, label: str, total: int | None = None) -> None:
        self.count: int = 0
        self.closed: bool = False
        columns: list[ProgressColumn]
        if total is None:
            # Minimization has no predictable total: constraints may restart
            # the optimizer, and convergence may stop it before maxIterations.
            columns = [
                SpinnerColumn(), TextColumn("[bold cyan]{task.description}"),
                TextColumn("{task.completed:.0f} iterations"),
                TimeElapsedColumn(),
            ]
        else:
            columns = [
                TextColumn("[bold cyan]{task.description}"), BarColumn(),
                TextColumn("{task.percentage:6.2f}%"), MofNCompleteColumn(),
                TextColumn("elapsed"), TimeElapsedColumn(),
                TextColumn("ETA"), TimeRemainingColumn(),
            ]
        self.progress: Progress = DetailProgress(
            *columns, console=Console(stderr=True), refresh_per_second=2,
            redirect_stdout=False, redirect_stderr=False,
        )
        detail: str = "T = -- K | Epot = -- kJ/mol" if total is not None else ""
        self.task_id: TaskID = self.progress.add_task(label, total=total, detail=detail)
        self.progress.start()

    def update(self, count: int, detail: str | None = None, force: bool = False) -> None:
        self.count = count
        if detail is None:
            self.progress.update(self.task_id, completed=count, refresh=force)
        else:
            self.progress.update(self.task_id, completed=count, detail=detail, refresh=force)

    def close(self) -> None:
        if not self.closed:
            self.progress.stop_task(self.task_id)
            self.progress.stop()
            self.closed = True


class MinimizationProgress(MinimizationReporter):
    """Report optimizer iterations without requesting early termination."""

    def __init__(self) -> None:
        super().__init__()
        self.display: TerminalProgress = TerminalProgress("Minimization")

    def report(self, iteration: int, x: Sequence[float], grad: Sequence[float], args: Mapping[str, float] | None = None) -> bool:
        # Count callbacks cumulatively: OpenMM may reset its local iteration index
        # when it strengthens the internal restraints that enforce constraints.
        detail: str = f"local iter {iteration + 1}"
        if args is not None and "system energy" in args:
            detail += f", E={args['system energy']:.6g} kJ/mol"
        if args is not None and "max constraint error" in args:
            detail += f", constraint error={args['max constraint error']:.3g}"
        self.display.update(self.display.count + 1, detail)
        return False

    def close(self) -> None:
        self.display.close()


def report_forces(simulation: Simulation, label: str) -> None:
    """Check the actual coordinates and forces, not just the total energy."""
    state: State = simulation.context.getState(getPositions=True, getForces=True, getEnergy=True)
    positions = state.getPositions(asNumpy=True).value_in_unit(nanometer)
    forces = state.getForces(asNumpy=True).value_in_unit(kilojoule/mole/nanometer)
    energy: float = float(state.getPotentialEnergy().value_in_unit(kilojoule/mole))
    if not (np.isfinite(positions).all() and np.isfinite(forces).all() and np.isfinite(energy)):
        raise RuntimeError(f"{label}: non-finite coordinates, forces or potential energy; cannot start MD")
    magnitudes = np.linalg.norm(forces, axis=1)
    index: int = int(np.argmax(magnitudes))
    atom = next(atom for atom in simulation.topology.atoms() if atom.index == index)
    print(f"{label}: Epot={energy:.8g} kJ/mol; max |F|={magnitudes[index]:.8g} kJ/mol/nm "
          f"at atom {index} (0-based), {atom.residue.chain.id}/{atom.residue.name}"
          f"{atom.residue.id}/{atom.name}", flush=True)


def minimize_on_platform(simulation: Simulation, platform_name: str | None,
                         tolerance: Quantity, steps: int,
                         reporter: MinimizationReporter | None) -> None:
    """Optionally minimize on CPU/Reference, then copy only coordinates back."""
    if platform_name is None or platform_name == simulation.context.getPlatform().getName():
        simulation.minimizeEnergy(tolerance=tolerance, maxIterations=steps, reporter=reporter)
        return
    # Keep every force and constraint, including current global parameters and
    # the periodic box.  This Context performs no MD and never replaces the MD
    # integrator, velocities, step count, time or RNG state.
    min_integrator: Integrator = XmlSerializer.deserialize(XmlSerializer.serialize(simulation.integrator))
    min_context: Context = Context(simulation.system, min_integrator, Platform.getPlatformByName(platform_name))
    min_context.setState(simulation.context.getState(getPositions=True, getParameters=True))
    LocalEnergyMinimizer.minimize(min_context, tolerance, steps, reporter)
    positions: Quantity = min_context.getState(getPositions=True).getPositions(asNumpy=True)
    if not np.isfinite(positions.value_in_unit(nanometer)).all():
        raise RuntimeError("Minimization produced non-finite coordinates")
    simulation.context.setPositions(positions)


class MDProgress:
    """Share energy states with the original StateDataReporter at nstout."""

    def __init__(self, simulation: Simulation, total: int, interval: int) -> None:
        self.start_step: int = simulation.currentStep
        self.interval: int = max(1, interval)
        # Same degrees-of-freedom convention as OpenMM's StateDataReporter.
        system: System = simulation.system
        mobile: list[bool] = [system.getParticleMass(i) > 0*dalton
                              for i in range(system.getNumParticles())]
        self.dof: int = 3 * sum(mobile)
        for i in range(system.getNumConstraints()):
            p1, p2, _ = system.getConstraintParameters(i)
            if mobile[p1] or mobile[p2]:
                self.dof -= 1
        if any(type(force) is CMMotionRemover for force in system.getForces()):
            self.dof -= 3
        self.temperature_k: float | None = None
        self.potential_energy_kj_mol: float | None = None
        self.display: TerminalProgress = TerminalProgress("MD", total)

    def describeNextReport(self, simulation: Simulation) -> dict[str, int | list[str]]:
        # OpenMM combines same-step energy requests; no extra reporting steps.
        return {"steps": self.interval - simulation.currentStep % self.interval, "include": ["energy"]}

    def report(self, simulation: Simulation, state: State) -> None:
        self.potential_energy_kj_mol = float(state.getPotentialEnergy().value_in_unit(kilojoule/mole))
        if self.dof > 0:
            self.temperature_k = float((2*state.getKineticEnergy() /
                                        (self.dof*MOLAR_GAS_CONSTANT_R)).value_in_unit(kelvin))
        temperature: str = "--" if self.temperature_k is None else f"{self.temperature_k:.2f}"
        detail: str = (f"T = {temperature} K | Epot = {self.potential_energy_kj_mol:,.2f} kJ/mol"
                       f" | step {simulation.currentStep}")
        self.display.update(simulation.currentStep - self.start_step, detail)

    def close(self, simulation: Simulation) -> None:
        self.display.update(simulation.currentStep - self.start_step)
        self.display.close()


